from aiogram.fsm.state import State, StatesGroup

# ---------------------------------------------------------------------------
# Майстерні (Конструктор карток)
# ---------------------------------------------------------------------------
class EditWorkshop(StatesGroup):
    enter_value  = State()  # Універсальний стан для вводу будь-якого поля


# ---------------------------------------------------------------------------
# Підтримка — відповідь на питання
# ---------------------------------------------------------------------------
class ReplySupport(StatesGroup):
    enter_text = State()


# ---------------------------------------------------------------------------
# Контент: FAQ 
# ---------------------------------------------------------------------------
class AddFAQ(StatesGroup):
    language = State()
    category = State()
    question = State()
    answer   = State()

class EditFAQ(StatesGroup):
    enter_value  = State()


# ---------------------------------------------------------------------------
# Контент: Загальна інформація 
# ---------------------------------------------------------------------------
class AddInfo(StatesGroup):
    language    = State()
    category    = State()
    information = State()

class EditInfo(StatesGroup):
    enter_value  = State()


# ---------------------------------------------------------------------------
# Адміністратори
# ---------------------------------------------------------------------------
class AddAdmin(StatesGroup):
    enter_telegram_id = State()  # Вводимо Telegram ID


# ---------------------------------------------------------------------------
# Налаштування адміна
# ---------------------------------------------------------------------------
class SettingsAdmin(StatesGroup):
    enter_name  = State()
    enter_phone = State()